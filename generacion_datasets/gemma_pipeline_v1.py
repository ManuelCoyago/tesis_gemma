def verificar_ganador(tablero, jugador):
    """Evalúa si el jugador indicado tiene 3 en línea actualmente."""
    lineas = [
        [0, 1, 2], [3, 4, 5], [6, 7, 8],  # Filas
        [0, 3, 6], [1, 4, 7], [2, 5, 8],  # Columnas
        [0, 4, 8], [2, 4, 6]              # Diagonales
    ]
    for linea in lineas:
        if tablero[linea[0]] == tablero[linea[1]] == tablero[linea[2]] == jugador:
            return True
    return False

def es_a_una_de_la_victoria(tablero, turno_actual):
    """
    Verifica si el estado actual está 'a una jugada de la victoria'.
    Revisa si al colocar una pieza en cualquier casilla vacía,
    el jugador actual gana (ataque) o el oponente ganaría (defensa/bloqueo).
    """
    oponente = 'O' if turno_actual == 'X' else 'X'

    for i in range(9):
        if tablero[i] == '-':
            # Simular jugada del jugador actual (¿Tiene jugada ganadora inminente?)
            tablero[i] = turno_actual
            si_gana_actual = verificar_ganador(tablero, turno_actual)
            tablero[i] = '-' # Revertir

            if si_gana_actual:
                return True

            # Simular jugada del oponente (¿El oponente tiene una amenaza activa que bloquear?)
            tablero[i] = oponente
            si_gana_oponente = verificar_ganador(tablero, oponente)
            tablero[i] = '-' # Revertir

            if si_gana_oponente:
                return True

    return False

def generar_estados_dfs(tablero, turno_actual, estados_visitados):
    str_tablero = "".join(tablero)
    if str_tablero in estados_visitados:
        return

    num_fichas = 9 - tablero.count('-')
    oponente = 'O' if turno_actual == 'X' else 'X'

    # -----------------------------------------------------------------
    # JERARQUÍA DE CATEGORIZACIÓN SEGÚN TUS ESPECIFICACIONES
    # -----------------------------------------------------------------
    # 1. ¿El juego ya terminó? (Terminales)
    es_fin_por_victoria = verificar_ganador(tablero, 'X') or verificar_ganador(tablero, 'O')
    es_fin_por_empate = (num_fichas == 9)

    if es_fin_por_victoria or es_fin_por_empate:
        etapa = "Terminales"

    # 2. ¿El juego sigue activo pero alguien está a un paso de ganar? (Finales)
    elif es_a_una_de_la_victoria(tablero, turno_actual):
        etapa = "Finales"

    # 3. ¿Tablero activo sin amenazas con 0, 1, 2 o 3 piezas? (Iniciales)
    elif num_fichas <= 3:
        etapa = "Iniciales"

    # 4. ¿Tablero activo sin amenazas con más de 3 piezas? (Intermedias)
    else:
        etapa = "Intermedias"

    formato_visual = f"{str_tablero[0:3]}/{str_tablero[3:6]}/{str_tablero[6:9]}"

    estados_visitados[str_tablero] = {
        "tablero": formato_visual,
        "num_fichas": num_fichas,
        "etapa_juego": etapa,
        "turno_de": turno_actual
    }

    # Condición de parada de la exploración DFS (No expandir nodos si el juego terminó)
    if es_fin_por_victoria or es_fin_por_empate:
        return

    # Expandir sub-árboles legales
    for i in range(9):
        if tablero[i] == '-':
            nuevo_tablero = list(tablero)
            nuevo_tablero[i] = turno_actual
            generar_estados_dfs(nuevo_tablero, oponente, estados_visitados)

